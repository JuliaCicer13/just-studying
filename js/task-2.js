
const num = Number(prompt());
let result;

switch( num ) {
    case 1: result = 'winter';
    break;
    case 2: result ='spring';
    break;
    case 3: result = 'summer';
    break;
    case 4: result = 'autumn';
    break;

    default: 'there is just only available from 1 to 4'
}

console.log(result);


